/// Holds the generated localization object active for the current app subtree.
final class PDFGeneratorLocalizationRuntime {
  PDFGeneratorLocalizationRuntime._();

  static PDFGeneratorLocalization? _current;

  static PDFGeneratorLocalization get current =>
      _current ?? lookupPDFGeneratorLocalization(const Locale('en'));

  static void bind(PDFGeneratorLocalization localization) {
    _current = localization;
  }
}

