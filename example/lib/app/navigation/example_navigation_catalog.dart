  static SuperNavNode<String> _leaf(
    String id,
    String title,
    IconData icon, {
    String? code,
    List<String> keywords = const <String>[],
  }) {
    return SuperNavNode<String>(
      id: id,
      label: Text(title),
      code: code,
      keywords: <String>[title, id, ...keywords],
      leadingIcon: Icon(icon),
      value: id,
    );
  }

  static SuperNavNode<String> _group(
    String id,
    String title,
    IconData icon,
    List<SuperNavNode<String>> children,
  ) {
    return SuperNavNode<String>(
      id: id,
      label: Text(title),
      keywords: <String>[title],
      leadingIcon: Icon(icon),
      children: children,
    );
  }
